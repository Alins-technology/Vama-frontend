/**
 * Generates src/data/treatmentIndex.js — just the slug / name / category of
 * every treatment, pulled from src/data/treatments.js.
 *
 * Why: treatments.js is ~160 KB of full page content (descriptions, FAQs,
 * articles). The Navbar, Footer, home stats and the blog auto-linker only need
 * names and slugs, but importing treatments.js put all of it into the main JS
 * bundle that every visitor downloads and parses before the page becomes
 * interactive — a big part of the mobile Total Blocking Time.
 *
 * Runs automatically before `npm run dev` and `npm run build`, so the index
 * never drifts from treatments.js. Edit treatments.js as usual.
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = fs.readFileSync(path.join(root, "src", "data", "treatments.js"), "utf-8");

// Node can't import image files, so swap each image import for an empty string.
const nodeSafe = src.replace(
  /^import\s+(\w+)\s+from\s+["'][^"']+\.(?:avif|jpe?g|png|webp|gif|svg)["'];?\s*$/gm,
  'const $1 = "";'
);
const tmp = path.join(os.tmpdir(), `vama-treatments-${process.pid}.mjs`);
fs.writeFileSync(tmp, nodeSafe);
let mod;
try {
  mod = await import(pathToFileURL(tmp).href);
} finally {
  fs.rmSync(tmp, { force: true });
}

const categories = mod.categories.map(({ slug, name }) => ({ slug, name }));
const treatments = mod.treatments.map(({ slug, name, category }) => ({ slug, name, category }));

const out = `// AUTO-GENERATED by scripts/gen-treatment-index.mjs from treatments.js.
// Do not edit by hand — change treatments.js and run \`npm run dev\` or \`npm run build\`.
// Lightweight list for the Navbar, Footer, stats and blog auto-linking, so the
// full treatments.js content stays out of the main JS bundle.

export const categories = ${JSON.stringify(categories, null, 2)};

export const treatmentIndex = ${JSON.stringify(treatments, null, 2)};

export const treatmentsByCategory = (category) =>
  treatmentIndex.filter((t) => t.category === category);
`;
fs.writeFileSync(path.join(root, "src", "data", "treatmentIndex.js"), out);
console.log(`treatmentIndex.js: ${categories.length} categories, ${treatments.length} treatments`);
